"""Bundle the editable modules and web assets into the portable sc.py file."""
from pathlib import Path
import ast

root=Path(__file__).resolve().parents[1]
parts=[]
for name in ('core','web','cli'):
    source=(root/'sc_manager'/(name+'.py')).read_text()
    lines=source.splitlines(keepends=True)
    tree=ast.parse(source)
    removals=[n for n in ast.walk(tree) if isinstance(n,ast.ImportFrom) and (n.module=='__future__' or n.level)]
    for node in sorted(removals,key=lambda n:n.lineno,reverse=True):
        del lines[node.lineno-1:node.end_lineno]
    source=''.join(lines)
    if name=='web':
        assets={file.name:file.read_text() for file in sorted((root/'sc_manager'/'static').iterdir()) if file.name in ('index.html','app.js','style.css')}
        source=source.replace('ASSET_CONTENT = {}','ASSET_CONTENT = '+repr(assets))
    parts.append(source)
header='#!/usr/bin/env python3\n"""Standalone SoundCloud upload desk. Copy this file anywhere; no project imports.\nInstall: pip install httpx filelock python-dotenv pillow fastapi uvicorn python-multipart\nGenerated by tools/build_standalone.py from the editable sources.\n"""\nfrom __future__ import annotations\n'
result=header+'\n\n'.join(parts)+'\n\nif __name__ == "__main__":\n    raise SystemExit(main())\n'
compile(result,'sc.py','exec')
(root/'sc.py').write_text(result)
(root/'sc.py').chmod(0o755)
print('Built standalone sc.py with embedded web assets')
